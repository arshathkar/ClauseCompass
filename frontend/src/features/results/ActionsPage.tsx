import { useState } from 'react';
import { CitationChip } from '../../components';

export function ActionsPage() {
  const [checkedItems, setCheckedItems] = useState<Record<string, boolean>>({});

  const checklist = [
    { id: 'c1', label: 'Clarify the exact notice period required before moving out.', clauseId: '4.1' },
    { id: 'c2', label: 'Confirm the list of standard deductions from the security deposit.', clauseId: '5.2' },
    { id: 'c3', label: 'Check who pays for major HVAC repairs.', clauseId: '7.1' }
  ];

  const toggleCheck = (id: string) => {
    setCheckedItems(prev => ({ ...prev, [id]: !prev[id] }));
  };

  const handleExport = () => {
    // Generate markdown
    const md = `# Legal Prep Brief\n\nGenerated by ClauseCompass\n\n## Checklist\n${checklist.map(c => `- [${checkedItems[c.id] ? 'x' : ' '}] ${c.label}`).join('\n')}`;
    const blob = new Blob([md], { type: 'text/markdown' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'clausecompass-brief.md';
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="flex flex-col h-full bg-white overflow-y-auto">
      <div className="max-w-3xl mx-auto w-full p-6 space-y-10 py-10">
        
        <section>
          <div className="mb-6 flex justify-between items-end border-b border-gray-200 pb-4">
            <div>
              <h2 className="text-2xl font-bold text-gray-900">Before you sign</h2>
              <p className="text-gray-600 mt-1">Checklist of items to resolve based on your document's risks.</p>
            </div>
            <button 
              onClick={handleExport}
              className="bg-brand text-white font-semibold py-2 px-4 rounded hover:bg-blue-700 focus:outline-none focus:ring-2 focus:ring-focus shadow-sm text-sm"
            >
              ↓ Export Brief
            </button>
          </div>

          <ul className="space-y-4">
            {checklist.map((item) => (
              <li key={item.id} className="flex items-start gap-3 bg-gray-50 p-4 rounded-lg border border-gray-200">
                <input 
                  type="checkbox" 
                  id={item.id}
                  checked={!!checkedItems[item.id]}
                  onChange={() => toggleCheck(item.id)}
                  className="mt-1 w-5 h-5 text-brand border-gray-300 rounded focus:ring-focus"
                />
                <div className="flex-1">
                  <label htmlFor={item.id} className={`block text-gray-800 font-medium ${checkedItems[item.id] ? 'line-through opacity-60' : ''}`}>
                    {item.label}
                  </label>
                  <div className="mt-2">
                    <CitationChip clauseId={item.clauseId} onClick={() => {}} />
                  </div>
                </div>
              </li>
            ))}
          </ul>
        </section>

        <section className="bg-blue-50 border border-blue-200 rounded-lg p-6">
          <h2 className="text-lg font-bold text-blue-900 mb-4">Questions for a Professional</h2>
          <ul className="list-disc pl-5 space-y-2 text-blue-800 font-medium">
            <li>What happens if the landlord sells the property during my lease?</li>
            <li>Is the penalty for late payment legally enforceable at this rate?</li>
          </ul>
        </section>

        <section>
          <h2 className="text-lg font-bold text-gray-900 mb-4">Resources (India)</h2>
          <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
            <a href="#" className="block p-4 border border-gray-200 rounded-lg hover:border-brand hover:shadow-sm focus:outline-none focus:ring-2 focus:ring-focus">
              <h3 className="font-bold text-brand mb-1">National Consumer Helpline</h3>
              <p className="text-sm text-gray-600">File grievances regarding services.</p>
              <span className="text-xs text-gray-400 mt-2 block">Last reviewed: Sep 2026</span>
            </a>
            <a href="#" className="block p-4 border border-gray-200 rounded-lg hover:border-brand hover:shadow-sm focus:outline-none focus:ring-2 focus:ring-focus">
              <h3 className="font-bold text-brand mb-1">Legal Services Authority (NALSA)</h3>
              <p className="text-sm text-gray-600">Free legal aid for eligible citizens.</p>
              <span className="text-xs text-gray-400 mt-2 block">Last reviewed: Sep 2026</span>
            </a>
          </div>
        </section>

      </div>
    </div>
  );
}
